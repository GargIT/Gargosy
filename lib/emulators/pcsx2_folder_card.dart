/// Makes [path] a PCSX2 folder memory card: a new folder card when nothing
/// is there, or the superblock added to a folder card that lacks it (the
/// saves in it stay). A file card at [path] is left alone.
void ensurePcsx2FolderCard(String path) {
  final type = io.FileSystemEntity.typeSync(path);
  if (type == io.FileSystemEntityType.file) return;
  final superblock = io.File(p.join(path, '_pcsx2_superblock'));
  if (superblock.existsSync()) return;
  io.Directory(path).createSync(recursive: true);
  superblock.writeAsBytesSync(pcsx2FolderCardSuperblock);
}
